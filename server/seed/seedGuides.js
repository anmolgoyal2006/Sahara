// SEED FUNCTION
// ─────────────────────────────────────────────

async function seedGuides () {
  console.log(`Starting seed — ${guides.length} guides to insert…`)

  for (const guide of guides) {
    const { steps, ...guideData } = guide

    // Upsert guide on slug
    const { data: upserted, error: guideErr } = await supabase
      .from('guides')
      .upsert(guideData, { onConflict: 'slug' })
      .select('id, slug')
      .single()

    if (guideErr) {
      console.error(`✗ Failed to upsert guide "${guide.slug}":`, guideErr.message)
      continue
    }

    const guideId = upserted.id
    console.log(`✓ Guide upserted: ${upserted.slug} (${guideId})`)

    // Delete existing steps for idempotency
    const { error: delErr } = await supabase
      .from('guide_steps')
      .delete()
      .eq('guide_id', guideId)

    if (delErr) {
      console.error(`  ✗ Failed to delete old steps for "${guide.slug}":`, delErr.message)
      continue
    }

    // Bulk insert fresh steps
    const stepsToInsert = steps.map(step => ({
      ...step,
      guide_id: guideId,
    }))

    const { error: stepsErr } = await supabase
      .from('guide_steps')
      .insert(stepsToInsert)

    if (stepsErr) {
      console.error(`  ✗ Failed to insert steps for "${guide.slug}":`, stepsErr.message)
    } else {
      console.log(`  ✓ ${steps.length} steps inserted for "${guide.slug}"`)
    }
  }

  console.log('\nSeed complete.')
}

seedGuides().catch(err => {
  console.error('Seed script failed:', err)
  process.exit(1)
})
